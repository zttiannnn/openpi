"""Real-Time Chunking (RTC) utilities for PyTorch.

RTC improves the smoothness of action chunks generated by diffusion/flow-matching
policies by guiding the denoising process towards the previous chunk's predictions.
"""

import math
from collections.abc import Callable
from dataclasses import dataclass

import numpy as np
import torch
from openpi.shared.normalize import NormStats


@dataclass
class RTCConfig:
    """Configuration for Real-Time Chunking guidance."""

    # Whether RTC is enabled
    enabled: bool = False
    # Attention schedule for prefix weights: "zeros" | "ones" | "linear" | "exp"
    prefix_attention_schedule: str = "linear"
    # Max guidance weight (if None, defaults to num_steps)
    max_guidance_weight: float | None = None
    # Execution horizon for building prefix weights
    execution_horizon: int = 10
    # Prior variance scale parameter
    sigma_d: float = 1.0
    # Match lerobot default behavior unless explicitly opting into direct error guidance.
    full_trajectory_alignment: bool = False


@dataclass(frozen=True)
class RTCRuntimeStats:
    """Runtime diagnostics for RTC chunk handoff quality."""

    action_index_before_inference: int
    leftover_len_at_send: int
    real_delay: int
    rtc_execution_horizon: int
    effective_guided_steps: int
    overlap_len: int
    overlap_l2_before: float | None
    overlap_l2_after: float | None


@dataclass(frozen=True)
class ActionChunkStats:
    """Per-chunk smoothness diagnostics for action trajectories."""

    joint_dims: int
    state_to_first_l2: float | None
    state_to_first_abs_max: float | None
    step_delta_l2_mean: float | None
    step_delta_l2_max: float | None
    step_delta_abs_max: float | None
    step_acc_l2_mean: float | None
    step_acc_l2_max: float | None
    step_acc_abs_max: float | None


@dataclass(frozen=True)
class ActionChunkJointStats:
    """Joint-wise chunk diagnostics for first-step and smoothness analysis."""

    joint_dims: int
    state_to_first: np.ndarray | None
    step_delta_abs_max: np.ndarray | None
    step_acc_abs_max: np.ndarray | None


@dataclass(frozen=True)
class BoundaryJumpStats:
    """Difference between the old queue head and the next queued action."""

    joint_dims: int
    delta: np.ndarray | None
    l2: float | None
    abs_max: float | None


def get_prefix_weights(
    start: int,
    end: int,
    total: int,
    schedule: str = "linear",
) -> torch.Tensor:
    """Compute prefix attention weights for RTC guidance.

    Generates a weight vector of shape (total,):
        [1.0, ..., 1.0, ramp↓, 0.0, ..., 0.0]
         ←── start ──→ ←end-start→ ←total-end→

    Args:
        start: Number of frozen prefix steps (inference delay).
        end: Execution horizon (end of ramp region).
        total: Total action horizon.
        schedule: Weight decay schedule ("zeros", "ones", "linear", "exp").

    Returns:
        Tensor of shape (total,) with values in [0, 1].
    """
    # Clamp to valid ranges
    start = min(max(start, 0), total)
    end = min(max(end, 0), total)
    start = min(start, end)

    weights = torch.zeros(total, dtype=torch.float32)

    if schedule == "zeros":
        # Only frozen prefix gets weight 1
        if start > 0:
            weights[:start] = 1.0

    elif schedule == "ones":
        # Everything up to end gets weight 1
        if end > 0:
            weights[:end] = 1.0

    elif schedule == "linear":
        # Frozen prefix: weight 1
        if start > 0:
            weights[:start] = 1.0
        # Ramp region: linear decay from ~1 to ~0
        ramp_len = end - start
        if ramp_len > 0:
            # Matches LeRobot convention: linspace(1, 0, steps+2)[1:-1]
            ramp_vals = torch.linspace(1.0, 0.0, ramp_len + 2)[1:-1]
            weights[start:end] = ramp_vals

    elif schedule == "exp":
        # Match lerobot's exponentially weighted linear ramp.
        if start > 0:
            weights[:start] = 1.0
        ramp_len = end - start
        if ramp_len > 0:
            ramp_vals = torch.linspace(1.0, 0.0, ramp_len + 2)[1:-1]
            ramp_vals = ramp_vals * torch.expm1(ramp_vals).div(math.e - 1.0)
            weights[start:end] = ramp_vals

    else:
        raise ValueError(f"Unknown RTC schedule: {schedule!r}")

    return weights


def _compute_overlap_l2(
    previous_actions: np.ndarray | None,
    new_actions: np.ndarray | None,
    real_delay: int,
) -> tuple[int, float | None]:
    if previous_actions is None or new_actions is None:
        return 0, None

    prev_arr = np.asarray(previous_actions, dtype=np.float32)
    new_arr = np.asarray(new_actions, dtype=np.float32)

    if prev_arr.ndim == 1:
        prev_arr = prev_arr[None, :]
    if new_arr.ndim == 1:
        new_arr = new_arr[None, :]

    trimmed_new_arr = new_arr[max(real_delay, 0) :]
    overlap_len = min(len(prev_arr), len(trimmed_new_arr))
    if overlap_len <= 0:
        return 0, None

    overlap_l2 = float(np.linalg.norm(prev_arr[:overlap_len] - trimmed_new_arr[:overlap_len]))
    return overlap_len, overlap_l2


def compute_rtc_runtime_stats(
    *,
    prev_raw_left_over: np.ndarray | None,
    prev_processed_left_over: np.ndarray | None,
    new_raw_actions: np.ndarray | None,
    new_processed_actions: np.ndarray | None,
    real_delay: int,
    leftover_len_at_send: int,
    rtc_execution_horizon: int,
    action_index_before_inference: int,
) -> RTCRuntimeStats:
    """Summarize whether RTC still has effective overlap at chunk handoff.

    `overlap_l2_before` compares raw (normalized) overlap, while
    `overlap_l2_after` compares processed/executed overlap after all runtime
    transforms applied to the chunk.
    """
    real_delay = max(int(real_delay), 0)
    leftover_len_at_send = max(int(leftover_len_at_send), 0)
    rtc_execution_horizon = max(int(rtc_execution_horizon), 0)
    action_index_before_inference = max(int(action_index_before_inference), 0)

    raw_overlap_len, raw_overlap_l2 = _compute_overlap_l2(prev_raw_left_over, new_raw_actions, real_delay)
    processed_overlap_len, processed_overlap_l2 = _compute_overlap_l2(
        prev_processed_left_over,
        new_processed_actions,
        real_delay,
    )
    effective_guided_steps = max(0, min(leftover_len_at_send, rtc_execution_horizon) - real_delay)
    overlap_len = processed_overlap_len if processed_overlap_len > 0 else raw_overlap_len

    return RTCRuntimeStats(
        action_index_before_inference=action_index_before_inference,
        leftover_len_at_send=leftover_len_at_send,
        real_delay=real_delay,
        rtc_execution_horizon=rtc_execution_horizon,
        effective_guided_steps=effective_guided_steps,
        overlap_len=overlap_len,
        overlap_l2_before=raw_overlap_l2,
        overlap_l2_after=processed_overlap_l2,
    )


def format_rtc_runtime_stats(stats: RTCRuntimeStats, *, chunk_idx: int | None = None) -> str:
    """Format RTC runtime diagnostics for always-visible terminal output."""

    prefix = "  RTC result:" if chunk_idx is None else f"  RTC result #{chunk_idx}:"
    overlap_l2_before = "n/a" if stats.overlap_l2_before is None else f"{stats.overlap_l2_before:.6f}"
    overlap_l2_after = "n/a" if stats.overlap_l2_after is None else f"{stats.overlap_l2_after:.6f}"
    return (
        f"{prefix} action_index_before_inference={stats.action_index_before_inference} "
        f"leftover_len_at_send={stats.leftover_len_at_send} "
        f"real_delay={stats.real_delay} "
        f"rtc_execution_horizon={stats.rtc_execution_horizon} "
        f"effective_guided_steps={stats.effective_guided_steps} "
        f"overlap={stats.overlap_len} "
        f"overlap_l2_before={overlap_l2_before} "
        f"overlap_l2_after={overlap_l2_after}"
    )


def get_rtc_boundary_risks(stats: RTCRuntimeStats) -> list[str]:
    """Summarize RTC boundary risks in user-facing wording."""

    reasons: list[str] = []
    if stats.leftover_len_at_send > 0 and stats.real_delay >= stats.leftover_len_at_send:
        reasons.append("delay exhausted leftover tail before the new chunk arrived")
    if stats.rtc_execution_horizon > 0 and stats.real_delay >= stats.rtc_execution_horizon:
        reasons.append("delay exceeded rtc_execution_horizon")
    if stats.effective_guided_steps <= 0:
        reasons.append("no effective guided steps remain at the executed boundary")
    return reasons


def compute_action_chunk_stats(
    actions: np.ndarray | torch.Tensor,
    *,
    state: np.ndarray | torch.Tensor | None = None,
    joint_dims: int = 6,
) -> ActionChunkStats:
    """Summarize first-step error, step deltas, and step accelerations for a chunk."""

    action_arr = np.asarray(actions, dtype=np.float32)
    if action_arr.ndim == 1:
        action_arr = action_arr[None, :]

    joint_dims = max(0, min(int(joint_dims), action_arr.shape[-1]))
    joint_actions = action_arr[:, :joint_dims]

    state_to_first_l2 = None
    state_to_first_abs_max = None
    if state is not None and joint_dims > 0:
        state_arr = np.asarray(state, dtype=np.float32).reshape(-1)
        if state_arr.shape[-1] >= joint_dims:
            state_delta = joint_actions[0] - state_arr[:joint_dims]
            state_to_first_l2 = float(np.linalg.norm(state_delta))
            state_to_first_abs_max = float(np.max(np.abs(state_delta)))

    step_delta_l2_mean = None
    step_delta_l2_max = None
    step_delta_abs_max = None
    if len(joint_actions) >= 2 and joint_dims > 0:
        step_deltas = np.diff(joint_actions, axis=0)
        step_delta_l2 = np.linalg.norm(step_deltas, axis=1)
        step_delta_l2_mean = float(np.mean(step_delta_l2))
        step_delta_l2_max = float(np.max(step_delta_l2))
        step_delta_abs_max = float(np.max(np.abs(step_deltas)))

    step_acc_l2_mean = None
    step_acc_l2_max = None
    step_acc_abs_max = None
    if len(joint_actions) >= 3 and joint_dims > 0:
        step_acc = np.diff(joint_actions, n=2, axis=0)
        step_acc_l2 = np.linalg.norm(step_acc, axis=1)
        step_acc_l2_mean = float(np.mean(step_acc_l2))
        step_acc_l2_max = float(np.max(step_acc_l2))
        step_acc_abs_max = float(np.max(np.abs(step_acc)))

    return ActionChunkStats(
        joint_dims=joint_dims,
        state_to_first_l2=state_to_first_l2,
        state_to_first_abs_max=state_to_first_abs_max,
        step_delta_l2_mean=step_delta_l2_mean,
        step_delta_l2_max=step_delta_l2_max,
        step_delta_abs_max=step_delta_abs_max,
        step_acc_l2_mean=step_acc_l2_mean,
        step_acc_l2_max=step_acc_l2_max,
        step_acc_abs_max=step_acc_abs_max,
    )


def format_action_chunk_stats(stats: ActionChunkStats, *, label: str) -> str:
    """Format chunk smoothness diagnostics for terminal output."""

    def fmt(value: float | None) -> str:
        return "n/a" if value is None else f"{value:.6f}"

    return (
        f"  {label}: joint_dims={stats.joint_dims} "
        f"state_to_first_l2={fmt(stats.state_to_first_l2)} "
        f"state_to_first_abs_max={fmt(stats.state_to_first_abs_max)} "
        f"step_delta_l2_mean={fmt(stats.step_delta_l2_mean)} "
        f"step_delta_l2_max={fmt(stats.step_delta_l2_max)} "
        f"step_delta_abs_max={fmt(stats.step_delta_abs_max)} "
        f"step_acc_l2_mean={fmt(stats.step_acc_l2_mean)} "
        f"step_acc_l2_max={fmt(stats.step_acc_l2_max)} "
        f"step_acc_abs_max={fmt(stats.step_acc_abs_max)}"
    )


def compute_action_chunk_joint_stats(
    actions: np.ndarray | torch.Tensor,
    *,
    state: np.ndarray | torch.Tensor | None = None,
    joint_dims: int = 6,
) -> ActionChunkJointStats:
    """Compute per-joint first-step gap and max delta/acceleration magnitudes."""

    action_arr = np.asarray(actions, dtype=np.float32)
    if action_arr.ndim == 1:
        action_arr = action_arr[None, :]

    joint_dims = max(0, min(int(joint_dims), action_arr.shape[-1]))
    joint_actions = action_arr[:, :joint_dims]

    state_to_first = None
    if state is not None and joint_dims > 0:
        state_arr = np.asarray(state, dtype=np.float32).reshape(-1)
        if state_arr.shape[-1] >= joint_dims:
            state_to_first = (joint_actions[0] - state_arr[:joint_dims]).astype(np.float32)

    step_delta_abs_max = None
    if len(joint_actions) >= 2 and joint_dims > 0:
        step_delta_abs_max = np.max(np.abs(np.diff(joint_actions, axis=0)), axis=0).astype(np.float32)

    step_acc_abs_max = None
    if len(joint_actions) >= 3 and joint_dims > 0:
        step_acc_abs_max = np.max(np.abs(np.diff(joint_actions, n=2, axis=0)), axis=0).astype(np.float32)

    return ActionChunkJointStats(
        joint_dims=joint_dims,
        state_to_first=state_to_first,
        step_delta_abs_max=step_delta_abs_max,
        step_acc_abs_max=step_acc_abs_max,
    )


def _format_vector(values: np.ndarray | None) -> str:
    if values is None:
        return "n/a"
    arr = np.asarray(values, dtype=np.float32).reshape(-1)
    return "[" + ", ".join(f"{value:.6f}" for value in arr) + "]"


def format_action_chunk_joint_stats(stats: ActionChunkJointStats, *, label: str) -> str:
    """Format joint-wise chunk diagnostics for terminal output."""

    return (
        f"  {label}: joint_dims={stats.joint_dims} "
        f"state_to_first={_format_vector(stats.state_to_first)} "
        f"step_delta_abs_max={_format_vector(stats.step_delta_abs_max)} "
        f"step_acc_abs_max={_format_vector(stats.step_acc_abs_max)}"
    )


def format_action_array_preview(
    actions: np.ndarray | torch.Tensor,
    *,
    label: str,
    max_rows: int = 3,
    precision: int = 3,
) -> str:
    """Format a compact preview of an action chunk for terminal inspection."""

    action_arr = np.asarray(actions, dtype=np.float32)
    if action_arr.ndim == 1:
        action_arr = action_arr[None, :]

    max_rows = max(int(max_rows), 1)
    precision = max(int(precision), 0)

    def _format_rows(rows: np.ndarray) -> str:
        rendered_rows = []
        for row in np.asarray(rows, dtype=np.float32):
            values = ", ".join(f"{value:.{precision}f}" for value in row)
            rendered_rows.append(f"[{values}]")
        return "[" + ", ".join(rendered_rows) + "]"

    if len(action_arr) <= max_rows * 2:
        return f"  {label}: shape={action_arr.shape} rows={_format_rows(action_arr)}"

    head = _format_rows(action_arr[:max_rows])
    tail = _format_rows(action_arr[-max_rows:])
    return f"  {label}: shape={action_arr.shape} head={head} tail={tail}"


def compute_boundary_jump_stats(
    *,
    previous_action: np.ndarray | torch.Tensor | None,
    next_action: np.ndarray | torch.Tensor | None,
    joint_dims: int = 6,
) -> BoundaryJumpStats:
    """Measure the jump from the old queue head to the next queued action."""

    if previous_action is None or next_action is None:
        return BoundaryJumpStats(joint_dims=max(int(joint_dims), 0), delta=None, l2=None, abs_max=None)

    prev_arr = np.asarray(previous_action, dtype=np.float32).reshape(-1)
    next_arr = np.asarray(next_action, dtype=np.float32).reshape(-1)
    joint_dims = max(0, min(int(joint_dims), prev_arr.shape[-1], next_arr.shape[-1]))

    if joint_dims == 0:
        return BoundaryJumpStats(joint_dims=0, delta=None, l2=None, abs_max=None)

    delta = (next_arr[:joint_dims] - prev_arr[:joint_dims]).astype(np.float32)
    return BoundaryJumpStats(
        joint_dims=joint_dims,
        delta=delta,
        l2=float(np.linalg.norm(delta)),
        abs_max=float(np.max(np.abs(delta))),
    )


def format_boundary_jump_stats(stats: BoundaryJumpStats, *, label: str) -> str:
    """Format queue-boundary jump diagnostics for terminal output."""

    l2 = "n/a" if stats.l2 is None else f"{stats.l2:.6f}"
    abs_max = "n/a" if stats.abs_max is None else f"{stats.abs_max:.6f}"
    return (
        f"  {label}: joint_dims={stats.joint_dims} "
        f"delta={_format_vector(stats.delta)} "
        f"l2={l2} "
        f"abs_max={abs_max}"
    )


def blend_action_chunks(
    *,
    old_actions: np.ndarray | torch.Tensor,
    new_actions: np.ndarray | torch.Tensor,
    curve: str,
    ema_alpha: float = 0.7,
    max_transition_steps: int = 0,
) -> np.ndarray:
    """Blend old and new action chunks over a bounded transition window.

    `max_transition_steps <= 0` preserves the previous behavior of blending across
    the full overlap. Positive values limit the blend to the first N overlap steps.
    """

    new_arr = np.asarray(new_actions, dtype=np.float32)
    if new_arr.ndim == 1:
        new_arr = new_arr[None, :]
    if len(new_arr) == 0:
        return new_arr.copy()

    old_arr = np.asarray(old_actions, dtype=np.float32)
    if old_arr.size == 0:
        return new_arr.copy()
    if old_arr.ndim == 1:
        old_arr = old_arr[None, :]
    if len(old_arr) == 0 or old_arr.shape[-1] == 0:
        return new_arr.copy()

    overlap = min(len(old_arr), len(new_arr))
    transition_steps = overlap if max_transition_steps <= 0 else min(overlap, int(max_transition_steps))
    result = new_arr.copy()

    for i in range(transition_steps):
        if curve == "linear":
            h = (i + 1) / (transition_steps + 1)
        elif curve == "cubic":
            t = (i + 1) / (transition_steps + 1)
            h = 3 * t**2 - 2 * t**3
        elif curve == "quintic":
            t = (i + 1) / (transition_steps + 1)
            h = 10 * t**3 - 15 * t**4 + 6 * t**5
        elif curve == "ema":
            h = float(ema_alpha)
        else:
            raise ValueError(f"Unknown transition curve: {curve!r}")
        result[i] = (1.0 - h) * old_arr[i] + h * new_arr[i]

    return result


def format_checkpoint_action_norm_stats(
    norm_stats: dict[str, NormStats] | None,
    *,
    joint_dims: int = 6,
) -> str | None:
    """Format checkpoint action normalization stats for quick terminal inspection."""

    if not norm_stats:
        return None

    stats = None
    for key in ("actions", "action"):
        if key in norm_stats:
            stats = norm_stats[key]
            break
    if stats is None:
        return None

    joint_dims = max(0, min(int(joint_dims), np.asarray(stats.mean).shape[-1]))
    mean = np.asarray(stats.mean, dtype=np.float32)[:joint_dims]
    std = np.asarray(stats.std, dtype=np.float32)[:joint_dims]
    q01 = None if stats.q01 is None else np.asarray(stats.q01, dtype=np.float32)[:joint_dims]
    q99 = None if stats.q99 is None else np.asarray(stats.q99, dtype=np.float32)[:joint_dims]
    return (
        "Checkpoint action norm stats: "
        f"mean={_format_vector(mean)} "
        f"std={_format_vector(std)} "
        f"q01={_format_vector(q01)} "
        f"q99={_format_vector(q99)}"
    )


def apply_rtc_guidance(
    *,
    x_t: torch.Tensor,
    prev_chunk_left_over: torch.Tensor | np.ndarray | None,
    inference_delay: int,
    time: float | torch.Tensor,
    original_denoise_step_partial: Callable[[torch.Tensor], torch.Tensor],
    rtc_config: RTCConfig,
    num_flow_matching_steps: int,
    execution_horizon: int | None = None,
) -> torch.Tensor:
    """Apply RTC guidance to one denoising step.

    This mirrors lerobot's RTCProcessor.denoise_step() behavior for the PyTorch
    OpenPI path so it can be tested independently from the model.
    """
    if prev_chunk_left_over is None or not rtc_config.enabled:
        return original_denoise_step_partial(x_t)

    tau = 1 - time
    x_t = x_t.clone().detach()

    squeezed = False
    if x_t.ndim < 3:
        x_t = x_t.unsqueeze(0)
        squeezed = True

    if isinstance(prev_chunk_left_over, np.ndarray):
        prev_chunk_left_over = torch.from_numpy(prev_chunk_left_over)
    prev_chunk_left_over = prev_chunk_left_over.to(dtype=torch.float32, device=x_t.device)
    if prev_chunk_left_over.ndim < 3:
        prev_chunk_left_over = prev_chunk_left_over.unsqueeze(0)

    if execution_horizon is None:
        execution_horizon = rtc_config.execution_horizon
    execution_horizon = min(execution_horizon, prev_chunk_left_over.shape[1])

    batch_size, action_chunk_size, action_dim = x_t.shape
    if prev_chunk_left_over.shape[1] < action_chunk_size or prev_chunk_left_over.shape[2] < action_dim:
        padded = torch.zeros(batch_size, action_chunk_size, action_dim, dtype=torch.float32, device=x_t.device)
        padded[:, : prev_chunk_left_over.shape[1], : prev_chunk_left_over.shape[2]] = prev_chunk_left_over
        prev_chunk_left_over = padded

    weights = (
        get_prefix_weights(
            inference_delay,
            execution_horizon,
            action_chunk_size,
            schedule=rtc_config.prefix_attention_schedule,
        )
        .to(x_t.device)
        .unsqueeze(0)
        .unsqueeze(-1)
    )

    time_tensor = torch.as_tensor(time, dtype=torch.float32, device=x_t.device)
    with torch.enable_grad():
        x_t.requires_grad_(True)
        v_t = original_denoise_step_partial(x_t)
        x1_t = x_t - time_tensor * v_t
        err = (prev_chunk_left_over - x1_t) * weights
        correction = err
        if not rtc_config.full_trajectory_alignment:
            correction = torch.autograd.grad(x1_t, x_t, err.detach().clone(), retain_graph=False)[0]

    max_guidance_weight = rtc_config.max_guidance_weight
    if max_guidance_weight is None:
        max_guidance_weight = num_flow_matching_steps

    max_guidance_weight = torch.as_tensor(max_guidance_weight, dtype=torch.float32, device=x_t.device)
    tau_tensor = torch.as_tensor(tau, dtype=torch.float32, device=x_t.device)
    squared_one_minus_tau = (1 - tau_tensor) ** 2
    prior_variance = torch.as_tensor(rtc_config.sigma_d**2, dtype=torch.float32, device=x_t.device)
    inv_r2 = (squared_one_minus_tau + tau_tensor**2 * prior_variance) / (squared_one_minus_tau * prior_variance)
    c = torch.nan_to_num((1 - tau_tensor) / tau_tensor, posinf=max_guidance_weight)
    guidance_weight = torch.nan_to_num(c * inv_r2, posinf=max_guidance_weight)
    guidance_weight = torch.minimum(guidance_weight, max_guidance_weight)

    result = v_t - guidance_weight * correction
    if squeezed:
        result = result.squeeze(0)
    return result


class RTCActionQueue:
    """Track raw and processed action chunks for RTC-style async execution."""

    def __init__(self, enabled: bool):
        self.enabled = enabled
        self.queue: np.ndarray | None = None
        self.original_queue: np.ndarray | None = None
        self.last_index = 0

    def get(self) -> np.ndarray | None:
        if self.queue is None or self.last_index >= len(self.queue):
            return None
        action = self.queue[self.last_index].copy()
        self.last_index += 1
        return action

    def empty(self) -> bool:
        return self.qsize() <= 0

    def qsize(self) -> int:
        if self.queue is None:
            return 0
        return len(self.queue) - self.last_index

    def get_action_index(self) -> int:
        return self.last_index

    def get_left_over(self) -> np.ndarray | None:
        if self.original_queue is None:
            return None
        return self.original_queue[self.last_index :].copy()

    def get_processed_left_over(self) -> np.ndarray | None:
        if self.queue is None:
            return None
        return self.queue[self.last_index :].copy()

    def merge(
        self,
        original_actions: np.ndarray,
        processed_actions: np.ndarray,
        real_delay: int,
        action_index_before_inference: int | None = 0,
    ) -> None:
        self._check_delays(real_delay, action_index_before_inference)

        if self.enabled:
            self.original_queue = np.asarray(original_actions)[real_delay:].copy()
            self.queue = np.asarray(processed_actions)[real_delay:].copy()
            self.last_index = 0
            return

        if self.queue is None:
            self.original_queue = np.asarray(original_actions).copy()
            self.queue = np.asarray(processed_actions).copy()
            self.last_index = 0
            return

        self.original_queue = np.concatenate([self.original_queue, np.asarray(original_actions)], axis=0)
        self.original_queue = self.original_queue[self.last_index :].copy()
        self.queue = np.concatenate([self.queue, np.asarray(processed_actions)], axis=0)
        self.queue = self.queue[self.last_index :].copy()
        self.last_index = 0

    def _check_delays(self, real_delay: int, action_index_before_inference: int | None) -> None:
        if action_index_before_inference is None:
            return
        indexes_diff = self.last_index - action_index_before_inference
        if indexes_diff != real_delay:
            raise ValueError(
                f"Action queue delay mismatch: indexes diff {indexes_diff} != real delay {real_delay}"
            )
