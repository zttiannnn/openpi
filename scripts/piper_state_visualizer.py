# ==================== Configuration ====================
# Action chunk period: 50 actions / 30Hz = 1.67s
ACTION_CHUNK_PERIOD = 50 / 30.0  # 1.67 seconds

# Unit Conversions
PULSE_TO_DEG = 0.001        # 1 Pulse = 0.001 Degree
DEG_TO_RAD = np.pi / 180.0  # 1 Degree = pi/180 Radians
PULSE_TO_RAD = PULSE_TO_DEG * DEG_TO_RAD  # 1 Pulse = ~1.745e-5 Radians

